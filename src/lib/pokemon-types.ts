export function typeEffectiveness(attack: PokemonType, defenders: readonly PokemonType[]): number {
  const row = CHART[attack];
  return defenders.reduce((value, defense) => value * (
    row.immune?.includes(defense) ? 0 : row.strong.includes(defense) ? 2 : row.weak.includes(defense) ? 0.5 : 1
  ), 1);
}

export function bestMatchup(attacker: readonly PokemonType[], defenders: readonly PokemonType[]) {
  return attacker.map((type) => ({ type, multiplier: typeEffectiveness(type, defenders) }))
    .sort((a, b) => b.multiplier - a.multiplier)[0];
}
